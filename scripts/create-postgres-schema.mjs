import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const source = path.join(root, "prisma", "schema.prisma");
const targetDirectory = path.join(root, "prisma", "postgres");
const target = path.join(targetDirectory, "schema.prisma");
const sqliteSchema = await readFile(source, "utf8");
const postgresSchema = sqliteSchema.replace('provider = "sqlite"', 'provider = "postgresql"');
if (postgresSchema === sqliteSchema) throw new Error("Could not locate the SQLite datasource provider");
await mkdir(targetDirectory, { recursive: true });
await writeFile(target, `// Generated from prisma/schema.prisma. Do not edit this file directly.\n${postgresSchema}`);
console.log(`Generated ${path.relative(root, target)}`);
